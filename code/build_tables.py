import numpy as np, time, pickle
from geometry import *
t0=time.time()
tnil = build_bundle_table(0, R=10.0, Z=24.0, h=0.02, ncs=6000, T=27.0, dt=0.005)
print("nil table", time.time()-t0, "inf cells:", np.isinf(tnil.tab).sum())
rng=np.random.default_rng(1)
q = np.stack([rng.uniform(0,8,20000), np.zeros(20000), rng.uniform(-15,15,20000)],-1)
ex = nil_dist_e(q); ap = tnil(np.hypot(q[:,0],q[:,1]), np.abs(q[:,2]))
err = ap-ex; print("Nil table vs exact: max abs err %.4f, mean %.5f, 99%% %.4f" % (np.abs(err).max(), np.abs(err).mean(), np.quantile(np.abs(err),0.99)))
t0=time.time()
tsl2 = build_bundle_table(-1, R=10.0, Z=24.0, h=0.02, ncs=6000, T=27.0, dt=0.005)
print("sl2 table", time.time()-t0, "inf cells:", np.isinf(tsl2.tab).sum())
ze = np.array([1.0, 3.0, 2*np.pi, 8.0, 12.0, 20.0])
exact = np.where(ze<=2*np.pi, ze, 2*np.pi*np.sqrt((ze/(2*np.pi)+1)**2/2-1))
print("SL2 fibre: table", tsl2(np.zeros(6), ze), "\n   exact", exact)
rr = np.array([0.5,1,2,4,6,8]); print("SL2 base:", tsl2(rr, np.zeros(6)), rr)
t0=time.time()
tsol = build_sol_table(U=5.0, Z=6.0, h=0.04, ndir=300000, T=8.5, dt=0.01)
print("sol table", time.time()-t0, "inf cells:", np.isinf(tsol.tab).sum())
xs = np.array([[0.5,0,0],[2,0,0],[10,0,0],[40,0,0],[0,0.5,0],[0,3,0],[0,20,0],[1,0,1],[1,0,-2],[3,0,2],[0,3,-2],[0,2,3],[0,0,1],[0,0,4.5]])
dx,dy = sol_dist_plane(xs); ex = np.where(xs[:,1]==0, dx, dy)
print("Sol plane checks:\n table", np.round(tsol(xs),3), "\n exact", np.round(ex,3))
pickle.dump({'nil':tnil,'sl2':tsl2,'sol':tsol}, open('tables.pkl','wb'))
